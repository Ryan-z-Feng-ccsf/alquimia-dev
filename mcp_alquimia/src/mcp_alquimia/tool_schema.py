"""Derive the LLM-facing tool descriptions and input schemas from code.

A tool docstring's summary paragraph becomes the tool description and its
Google-style ``Args:`` entries become the parameter descriptions; the paragraphs
in between are developer notes and are not sent. Pydantic schemas are compacted
for the model: only the first paragraph of a model docstring is kept and titles
are dropped. Validation is unaffected; only the advertised schema changes.
"""

import inspect
import re
from typing import Any

# Keys whose values map names to schemas rather than holding keywords.
_NAME_MAPS = {"properties", "$defs", "patternProperties"}

# Advertised to nobody: limits still enforced by validation.
_DROPPED_KEYWORDS = {"title", "propertyNames"}

# e.g. "session_id: text" or "limit (int): text"
_ARG_ENTRY = re.compile(r"^(\w+)(?:\s*\([^)]*\))?:\s*(.*)$")

# e.g. Returns: / Raises:
_SECTION = re.compile(r"^[A-Z]\w*:$")


def _one_line(text: str) -> str:
    """Collapse whitespace, including newlines, to single spaces."""
    return " ".join(text.split())


def first_paragraph(text: str) -> str:
    """The text before its first blank line, on one line."""
    return _one_line(inspect.cleandoc(text).split("\n\n", 1)[0])


def split_docstring(docstring: str | None) -> tuple[str, dict[str, str]]:
    """Read a Google-style docstring's summary and Args entries.

    Args:
        docstring: Function docstring; None reads as empty.

    Returns:
        The first paragraph on one line, and each Args entry's name mapped to its
        text on one line, continuation lines included.
    """
    # Clean up the relative indentation, get the list
    lines = inspect.cleandoc(docstring or "").splitlines()
    summary = first_paragraph("\n".join(lines))
    arguments: dict[str, str] = {}
    # Check "Args:"
    in_args = False
    current = None
    # Indentation of the first Args entry; any consistent width is accepted
    entry_indent = None
    for line in lines:
        if line == "Args:":
            in_args = True
            continue
        if not in_args:
            continue
        
        # Intercept unindented, non-empty lines
        if line and not line[0].isspace():
            if _SECTION.match(line):
                break  # Returns:, Raises: and other sections end Args
            # Ignore unexpected unindented lines and keep scanning
            continue
        
        # Args: block
        stripped = line.strip()
        if not stripped:
            continue
        indent = len(line) - len(line.lstrip())
        if entry_indent is None:
            entry_indent = indent
        entry = _ARG_ENTRY.match(stripped)
        # Entries sit at the first entry's indentation; deeper lines continue one
        # e.g. "session_id: text"
        # group(1) = session_id
        # group(2) = text
        if entry and indent == entry_indent:
            current = entry.group(1)
            arguments[current] = entry.group(2)
        elif current and indent > entry_indent:
            arguments[current] += " " + stripped
    return summary, {name: _one_line(text) for name, text in arguments.items()}


def _collapse_optional(node: dict[str, Any]) -> dict[str, Any]:
    """Advertise `X | None = None` as plain X: omitting the field means none."""
    # Check if the schema node allows multiple types via 'anyOf'
    options = node.get("anyOf")
    # Target the specific pattern generated by Pydantic for Optional fields:
    # 1. It must be a list of exactly 2 options.
    # 2. One of those options must be explicitly {"type": "null"}.
    # 3. The default value of this field must be None (null).
    if (
        isinstance(options, list) and len(options) == 2
        and {"type": "null"} in options and node.get("default", None) is None
    ):
        # Extract the actual data type (the non-null option)
        (kept,) = [option for option in options if option != {"type": "null"}]
        
        # Gather the rest of the node's metadata (like descriptions, constraints), 
        # but strip out the 'anyOf' and 'default' keys since we are flattening it
        rest = {key: value for key, value in node.items() if key not in ("anyOf", "default")}
        
        # Merge the actual type definition with the remaining metadata
        return {**kept, **rest}
    
    # Return the node unmodified if it doesn't match the Optional pattern
    return node


def compact_schema(schema: Any) -> Any:
    """Return an LLM-oriented copy of a JSON schema.

    Drops titles and propertyNames, keeps the first paragraph of descriptions,
    and turns optional ``anyOf: [X, null]`` fields defaulting to null into X.
    Ranges are left as pydantic writes them; see agent_input_coercion.lenient_float
    for keeping them standard.

    Args:
        schema: Schema produced by pydantic, or any value nested in one.

    Returns:
        A new schema; the input is not modified.
    """
    # Recursively process every item if the current schema part is a list
    if isinstance(schema, list):
        return [compact_schema(item) for item in schema]
    
    # Base case: if it's a primitive value (string, int, bool, etc.), return it as-is
    if not isinstance(schema, dict):
        return schema
    compacted: dict[str, Any] = {}
    
    # First, attempt to collapse Optional/null patterns.
    # Then iterate over the resulting dictionary's key-value pairs.
    for key, value in _collapse_optional(schema).items():
        
        # Drop title and propertyNames
        if key in _DROPPED_KEYWORDS:
            continue

        # Protect user-defined names inside "properties", "$defs", etc.
        # We iterate through them, keeping the user's key (name) exactly as-is, 
        # and only recurse into their inner schema definition (item)
        if key in _NAME_MAPS and isinstance(value, dict):
            compacted[key] = {name: compact_schema(item) for name, item in value.items()}
            
        # Shorten long descriptions to just the first paragraph to reduce verbosity
        elif key == "description" and isinstance(value, str):
            compacted[key] = first_paragraph(value)
            
        # For all other standard JSON Schema keywords, recursively compact their values
        else:
            compacted[key] = compact_schema(value)
    return compacted
